import CoreGraphics

// MARK: - CGFloat Spacing Extension

extension CGFloat {
    /// 2 pt - Tiny spacing for very close elements (e.g. badge padding)
    static let pt2: CGFloat = 2
    
    /// 4 pt - Extra small spacing for minor related elements
    static let pt4: CGFloat = 4
    
    /// 8 pt - Small spacing for grouped list items/text blocks
    static let pt8: CGFloat = 8
    
    /// 12 pt - Medium-small spacing
    static let pt12: CGFloat = 12
    
    /// 16 pt - Medium spacing for standard padding and view edges
    static let pt16: CGFloat = 16
    
    /// 20 pt - Medium-large spacing for section stacks
    static let pt20: CGFloat = 20
    
    /// 24 pt - Large spacing for major blocks
    static let pt24: CGFloat = 24
    
    /// 32 pt - Extra large spacing for page layout containers
    static let pt32: CGFloat = 32
    
    /// 48 pt - Double extra large spacing
    static let pt48: CGFloat = 48
}
